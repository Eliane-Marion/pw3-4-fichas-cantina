CREATE DATABASE fichas_cantina
USE fichas_cantina

CREATE TABLE TBL_ALUNO (
    ID_ALUNO BIGINT IDENTITY (1, 1) NOT NULL PRIMARY KEY, 
    TX_NOME_ALUNO VARCHAR(60) NOT NULL,
    NR_MATRICULA INT NOT NULL,
    NR_SALDO FLOAT NOT NULL, 
    BO_STATUS VARCHAR(10) NOT NULL, 
    
    CONSTRAINT CHK_BO_STATUS CHECK (BO_STATUS IN ('ATIVO', 'INATIVO')) 
);